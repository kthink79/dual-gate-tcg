package com.game.tcg.core.model

/**
 * 카드 도감의 정식 등록 기록 (이름·칭호·속성·ATK·DEF·코스트·스킬).
 *
 * 2026-11-26 기준 **193명 전원**을 이 표 하나에 등록한다.
 * (No.1~169 + No.176·177·178·179·180·181·182·185~189 신규 12인 + No.184 아메넷
 *  + No.190~199 신규 10인 + No.200 셀레스티아(200번째 기념 카드) = 193명,
 *  캐릭터당 전투·일상·데이트·미니어처 4종 비주얼 = JPG 772장 + 중간 보스 6인 24장)
 *
 * 도감·서약·덱·로비·전투·탐색은 모두 이 카탈로그를 단일 진실 원천으로 쓴다.
 * 이름·칭호는 배치별 제작 기록(프롬프트 전체집 · 명단 문서 · 제작 보고)에서 그대로 옮겼고,
 * 수치 원문이 남아 있지 않은 일부 배치(91~114)는 같은 밸런스 스케일로 책정했다.
 */
data class CharacterRecord(
    val id: Int,                      // 도감 번호 (드로어블 접미사 번호와 동일)
    val name: String,                 // 표시 이름 (예: "세라피엘")
    val title: String,                // 칭호 (예: "태양의 대천사")
    val element: Element,
    val atk: Int,
    val def: Int,
    val baseCost: Int,                // 소환 마나 코스트
    val skill: String,
    val isDemonLord: Boolean = false,
    val disguiseName: String? = null, // 마왕의 일상 위장 신분 이름
    val bondSeed: Int = 0,            // 합류 시점 호감도
    val isMidBoss: Boolean = false    // 중간 보스(No.170~175) — 적 전용, 클리어 후 연성 가능
) {
    /** 카드 전면에 쓰는 전체 이름 */
    val fullName: String get() = "$title $name"

    /** 전장 최대 HP — DEF 기반 (기존 카드 값 6000/4200/5200/7000과 같은 계수) */
    val maxHp: Int
        get() = when {
            id == 1 -> 6000
            id == 2 -> 4200
            id == 3 -> 5200
            id == 112 -> 7000
            isMidBoss -> (def * 1.8).toInt()   // 중간 보스는 두꺼운 HP
            else -> (def * 0.85).toInt()
        }

    /** 이 기록으로 실제 전투 카드를 만든다 */
    fun toCard(bondLevel: Int = bondSeed): TcgCard = TcgCard(
        id = id,
        name = fullName,
        element = element,
        baseCost = baseCost,
        atk = atk,
        def = def,
        bondLevel = bondLevel,
        skillText = skill,
        category = CardCategory.CHARACTER
    )
}

